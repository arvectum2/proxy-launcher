    static func text(_ russian: String) -> String {
        let language = AppL10n.effectiveLanguage
        if language == "ru" { return russian }
        if let translated = priority[language]?[russian] { return translated }
        let contextual = AppL10n.tr(russian, table: "SmartExclusions")
        if contextual != russian { return contextual }
        if let fallback = english[russian] { return fallback }
        let existing = AppL10n.tr(russian)
        if existing != russian { return existing }
        // Never expose raw Russian-only validation or system errors after a
        // user switches the app to another language. No private host/error
        // details are inserted into fallback strings.
        if russian.unicodeScalars.contains(where: { (0x0400...0x052F).contains($0.value) }) {
            return "Could not complete the operation. Check the website address and try again."
        }
        return russian
    }

